export type ChatLabels = { [K in keyof (typeof CHAT_LABELS)['en']]: string };
export type ChatMessageCode = Extract<keyof ChatLabels, `msg_${string}`>;

/** A form's or a page's message in the reader's language: its code's label, or OBP-API's own words. */
export function chatMessage(labels: ChatLabels, result: { code?: string; message?: string } | null | undefined): string {
	if (!result) return '';
	if (result.code && result.code in labels) return labels[result.code as keyof ChatLabels];
	return result.message ?? '';
}
